-- 1. Impide borrar un usuario que tiene prestamos activos
CREATE OR REPLACE TRIGGER TRG_BLOQUEAR_BAJA_USUARIO_CON_PRESTAMOS
BEFORE DELETE ON USUARIOS
FOR EACH ROW
DECLARE
    CURSOR C_PRESTAMOS_ACTIVOS IS
        SELECT ID_PRESTAMO FROM PRESTAMOS
        WHERE CEDULA = :OLD.CEDULA AND ESTADO = 'ACTIVO';
    V_EXISTE NUMBER := 0;
BEGIN
    FOR REG IN C_PRESTAMOS_ACTIVOS LOOP
        V_EXISTE := 1;
        EXIT;
    END LOOP;
    IF V_EXISTE = 1 THEN
        RAISE_APPLICATION_ERROR(-20040, 'No se puede eliminar un usuario con prestamos activos.');
    END IF;
END;
/

-- 2. Valida que la fecha esperada sea posterior a la fecha del prestamo (defensa extra a nivel de tabla)
CREATE OR REPLACE TRIGGER TRG_VALIDAR_FECHAS_PRESTAMO
BEFORE INSERT ON PRESTAMOS
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_DEVOLUCION_ESPERADA <= :NEW.FECHA_PRESTAMO THEN
        RAISE_APPLICATION_ERROR(-20041, 'La fecha esperada de devolucion debe ser posterior a la fecha del prestamo.');
    END IF;
END;
/

-- 3. Genera la multa automaticamente cuando se registra la devolucion tardia
CREATE OR REPLACE TRIGGER TRG_GENERAR_MULTA_AUTOMATICA
AFTER UPDATE OF FECHA_DEVOLUCION_REAL ON PRESTAMOS
FOR EACH ROW
WHEN (NEW.FECHA_DEVOLUCION_REAL IS NOT NULL)
DECLARE
    V_DIAS NUMBER;
BEGIN
    V_DIAS := TRUNC(:NEW.FECHA_DEVOLUCION_REAL) - TRUNC(:NEW.FECHA_DEVOLUCION_ESPERADA);
    IF V_DIAS > 0 THEN
        PKG_MULTAS_ATRASOS.GENERAR_MULTA_DIRECTA(:NEW.ID_PRESTAMO, :NEW.CEDULA, V_DIAS);
    END IF;
END;
/

-- 4. Auditoria de cambios en USUARIOS
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_USUARIOS
AFTER INSERT OR UPDATE OR DELETE ON USUARIOS
FOR EACH ROW
DECLARE
    V_OPERACION VARCHAR2(10);
BEGIN
    IF INSERTING THEN V_OPERACION := 'INSERT';
    ELSIF UPDATING THEN V_OPERACION := 'UPDATE';
    ELSE V_OPERACION := 'DELETE';
    END IF;

    PKG_AUDITORIA.REGISTRAR_EVENTO('USUARIOS', V_OPERACION,
        'Cedula afectada: ' || NVL(:NEW.CEDULA, :OLD.CEDULA));
END;
/

