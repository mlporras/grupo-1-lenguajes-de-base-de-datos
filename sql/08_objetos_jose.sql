CREATE OR REPLACE PACKAGE PKG_AUDITORIA AS
    PROCEDURE REGISTRAR_EVENTO(
        P_TABLA     IN VARCHAR2,
        P_OPERACION IN VARCHAR2,
        P_DETALLE   IN VARCHAR2
    );
    PROCEDURE LISTAR_CAMBIOS_TABLA(
        P_TABLA     IN  VARCHAR2,
        P_TOTAL     OUT NUMBER,
        P_RESULTADO OUT SYS_REFCURSOR
    );
    PROCEDURE PURGAR_AUDITORIA(P_DIAS IN NUMBER);
    FUNCTION FN_TOTAL_EVENTOS_TABLA(P_TABLA IN VARCHAR2) RETURN NUMBER;
END PKG_AUDITORIA;
/

CREATE OR REPLACE PACKAGE BODY PKG_AUDITORIA AS

    PROCEDURE REGISTRAR_EVENTO(
        P_TABLA     IN VARCHAR2,
        P_OPERACION IN VARCHAR2,
        P_DETALLE   IN VARCHAR2
    ) IS
    BEGIN
        INSERT INTO AUDITORIA_LOG (ID_LOG, TABLA_AFECTADA, OPERACION, USUARIO_DB, FECHA_HORA, DETALLE)
        VALUES (SEQ_AUDITORIA_LOG.NEXTVAL, P_TABLA, P_OPERACION, USER, SYSDATE, P_DETALLE);
    END REGISTRAR_EVENTO;

    PROCEDURE LISTAR_CAMBIOS_TABLA(
        P_TABLA     IN  VARCHAR2,
        P_TOTAL     OUT NUMBER,
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
        CURSOR C_LOGS IS
            SELECT ID_LOG FROM AUDITORIA_LOG WHERE TABLA_AFECTADA = P_TABLA;
    BEGIN
        P_TOTAL := 0;
        FOR REG IN C_LOGS LOOP
            P_TOTAL := P_TOTAL + 1;
        END LOOP;

        OPEN P_RESULTADO FOR
            SELECT TABLA_AFECTADA, OPERACION, USUARIO_DB, FECHA_HORA, DETALLE
            FROM AUDITORIA_LOG
            WHERE TABLA_AFECTADA = P_TABLA
            ORDER BY FECHA_HORA DESC;
    END LISTAR_CAMBIOS_TABLA;

    PROCEDURE PURGAR_AUDITORIA(P_DIAS IN NUMBER) IS
        CURSOR C_ANTIGUOS IS
            SELECT ID_LOG FROM AUDITORIA_LOG WHERE FECHA_HORA < SYSDATE - P_DIAS;
    BEGIN
        FOR REG IN C_ANTIGUOS LOOP
            DELETE FROM AUDITORIA_LOG WHERE ID_LOG = REG.ID_LOG;
        END LOOP;
    END PURGAR_AUDITORIA;

    FUNCTION FN_TOTAL_EVENTOS_TABLA(P_TABLA IN VARCHAR2) RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_EVENTOS IS
            SELECT ID_LOG FROM AUDITORIA_LOG WHERE TABLA_AFECTADA = P_TABLA;
    BEGIN
        FOR REG IN C_EVENTOS LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_TOTAL_EVENTOS_TABLA;

END PKG_AUDITORIA;
/

