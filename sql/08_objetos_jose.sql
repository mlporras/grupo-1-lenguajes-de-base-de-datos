CREATE OR REPLACE PACKAGE PKG_MULTAS_ATRASOS AS
    FUNCTION FN_CALCULAR_DIAS_ATRASO(P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE) RETURN NUMBER;
    PROCEDURE GENERAR_MULTA(P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE);
    PROCEDURE GENERAR_MULTA_DIRECTA(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE,
        P_CEDULA      IN PRESTAMOS.CEDULA%TYPE,
        P_DIAS        IN NUMBER
    );
    PROCEDURE GENERAR_MULTAS_AUTOMATICAS;
    PROCEDURE LISTAR_MULTAS_PENDIENTES(P_RESULTADO OUT SYS_REFCURSOR);
    PROCEDURE PAGAR_MULTA(P_ID_MULTA IN MULTAS.ID_MULTA%TYPE);
END PKG_MULTAS_ATRASOS;
/

CREATE OR REPLACE PACKAGE BODY PKG_MULTAS_ATRASOS AS

    FUNCTION FN_CALCULAR_DIAS_ATRASO(P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE) RETURN NUMBER IS
        CURSOR C_PRESTAMO IS
            SELECT FECHA_DEVOLUCION_ESPERADA,
                   NVL(FECHA_DEVOLUCION_REAL, SYSDATE) AS FECHA_COMPARAR
            FROM PRESTAMOS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
        V_PRESTAMO C_PRESTAMO%ROWTYPE;
        V_DIAS NUMBER := 0;
    BEGIN
        OPEN C_PRESTAMO;
        FETCH C_PRESTAMO INTO V_PRESTAMO;
        CLOSE C_PRESTAMO;

        V_DIAS := TRUNC(V_PRESTAMO.FECHA_COMPARAR) - TRUNC(V_PRESTAMO.FECHA_DEVOLUCION_ESPERADA);
        IF V_DIAS < 0 THEN
            V_DIAS := 0;
        END IF;
        RETURN V_DIAS;
    END FN_CALCULAR_DIAS_ATRASO;

    -- Uso normal (fuera de triggers): consulta PRESTAMOS directamente
    PROCEDURE GENERAR_MULTA(P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE) IS
        V_DIAS   NUMBER;
        V_CEDULA PRESTAMOS.CEDULA%TYPE;
        V_MONTO_POR_DIA CONSTANT NUMBER := 500;
        V_YA_EXISTE NUMBER := 0;
        CURSOR C_EXISTENTE IS
            SELECT ID_MULTA FROM MULTAS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
    BEGIN
        FOR REG IN C_EXISTENTE LOOP
            V_YA_EXISTE := 1;
        END LOOP;
        IF V_YA_EXISTE = 1 THEN
            RETURN;
        END IF;

        V_DIAS := FN_CALCULAR_DIAS_ATRASO(P_ID_PRESTAMO);
        IF V_DIAS > 0 THEN
            SELECT CEDULA INTO V_CEDULA FROM PRESTAMOS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
            INSERT INTO MULTAS (ID_MULTA, ID_PRESTAMO, CEDULA, MONTO, DIAS_ATRASO, FECHA_GENERACION, ESTADO_PAGO)
            VALUES (SEQ_MULTAS.NEXTVAL, P_ID_PRESTAMO, V_CEDULA, V_DIAS * V_MONTO_POR_DIA, V_DIAS, SYSDATE, 'PENDIENTE');
        END IF;
    END GENERAR_MULTA;

    -- Version "directa": NO consulta PRESTAMOS (recibe los datos ya calculados).
    PROCEDURE GENERAR_MULTA_DIRECTA(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE,
        P_CEDULA      IN PRESTAMOS.CEDULA%TYPE,
        P_DIAS        IN NUMBER
    ) IS
        V_MONTO_POR_DIA CONSTANT NUMBER := 500;
        V_YA_EXISTE NUMBER := 0;
        CURSOR C_EXISTENTE_DIRECTA IS
            SELECT ID_MULTA FROM MULTAS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
    BEGIN
        FOR REG IN C_EXISTENTE_DIRECTA LOOP
            V_YA_EXISTE := 1;
        END LOOP;

        IF V_YA_EXISTE = 0 AND P_DIAS > 0 THEN
            INSERT INTO MULTAS (ID_MULTA, ID_PRESTAMO, CEDULA, MONTO, DIAS_ATRASO, FECHA_GENERACION, ESTADO_PAGO)
            VALUES (SEQ_MULTAS.NEXTVAL, P_ID_PRESTAMO, P_CEDULA, P_DIAS * V_MONTO_POR_DIA, P_DIAS, SYSDATE, 'PENDIENTE');
        END IF;
    END GENERAR_MULTA_DIRECTA;

    PROCEDURE GENERAR_MULTAS_AUTOMATICAS IS
        CURSOR C_ATRASADOS IS
            SELECT ID_PRESTAMO FROM PRESTAMOS
            WHERE ESTADO = 'ACTIVO' AND FECHA_DEVOLUCION_ESPERADA < TRUNC(SYSDATE);
    BEGIN
        FOR REG IN C_ATRASADOS LOOP
            GENERAR_MULTA(REG.ID_PRESTAMO);
        END LOOP;
    END GENERAR_MULTAS_AUTOMATICAS;

    PROCEDURE LISTAR_MULTAS_PENDIENTES(P_RESULTADO OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT M.ID_MULTA, M.CEDULA, U.NOMBRE, U.APELLIDOS, M.MONTO, M.DIAS_ATRASO
            FROM MULTAS M
            JOIN USUARIOS U ON U.CEDULA = M.CEDULA
            WHERE M.ESTADO_PAGO = 'PENDIENTE';
    END LISTAR_MULTAS_PENDIENTES;

    PROCEDURE PAGAR_MULTA(P_ID_MULTA IN MULTAS.ID_MULTA%TYPE) IS
    BEGIN
        UPDATE MULTAS SET ESTADO_PAGO = 'PAGADA' WHERE ID_MULTA = P_ID_MULTA;
    END PAGAR_MULTA;

END PKG_MULTAS_ATRASOS;
/

