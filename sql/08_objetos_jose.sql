CREATE OR REPLACE FUNCTION FN_TOTAL_MULTAS_USUARIO(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
    V_TOTAL NUMBER := 0;
    CURSOR C_MULTAS_USUARIO IS
        SELECT ID_MULTA FROM MULTAS WHERE CEDULA = P_CEDULA;
BEGIN
    FOR REG IN C_MULTAS_USUARIO LOOP
        V_TOTAL := V_TOTAL + 1;
    END LOOP;
    RETURN V_TOTAL;
END FN_TOTAL_MULTAS_USUARIO;
/

CREATE OR REPLACE FUNCTION FN_MONTO_TOTAL_MULTAS_PENDIENTES(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
    V_MONTO NUMBER;
BEGIN
    SELECT NVL(SUM(MONTO), 0) INTO V_MONTO
    FROM MULTAS WHERE CEDULA = P_CEDULA AND ESTADO_PAGO = 'PENDIENTE';
    RETURN V_MONTO;
END FN_MONTO_TOTAL_MULTAS_PENDIENTES;
/

CREATE OR REPLACE FUNCTION FN_PROMEDIO_DIAS_PRESTAMO RETURN NUMBER IS
    V_PROMEDIO NUMBER;
BEGIN
    SELECT NVL(ROUND(AVG(FECHA_DEVOLUCION_REAL - FECHA_PRESTAMO), 1), 0) INTO V_PROMEDIO
    FROM PRESTAMOS WHERE FECHA_DEVOLUCION_REAL IS NOT NULL;
    RETURN V_PROMEDIO;
END FN_PROMEDIO_DIAS_PRESTAMO;
/

CREATE OR REPLACE FUNCTION FN_DIAS_RESTANTES_PRESTAMO(P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE) RETURN NUMBER IS
    V_FECHA_ESPERADA PRESTAMOS.FECHA_DEVOLUCION_ESPERADA%TYPE;
BEGIN
    SELECT FECHA_DEVOLUCION_ESPERADA INTO V_FECHA_ESPERADA
    FROM PRESTAMOS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
    RETURN TRUNC(V_FECHA_ESPERADA) - TRUNC(SYSDATE);
END FN_DIAS_RESTANTES_PRESTAMO;
/

CREATE OR REPLACE FUNCTION FN_PORCENTAJE_MATERIALES_DISPONIBLES RETURN NUMBER IS
    V_TOTAL       NUMBER;
    V_DISPONIBLES NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL FROM MATERIALES;
    IF V_TOTAL = 0 THEN
        RETURN 0;
    END IF;
    SELECT COUNT(*) INTO V_DISPONIBLES FROM MATERIALES WHERE ESTADO = 'DISPONIBLE';
    RETURN ROUND((V_DISPONIBLES / V_TOTAL) * 100, 1);
END FN_PORCENTAJE_MATERIALES_DISPONIBLES;
/

CREATE OR REPLACE FUNCTION FN_ANTIGUEDAD_USUARIO_DIAS(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
    V_FECHA_REGISTRO USUARIOS.FECHA_REGISTRO%TYPE;
BEGIN
    SELECT FECHA_REGISTRO INTO V_FECHA_REGISTRO FROM USUARIOS WHERE CEDULA = P_CEDULA;
    RETURN TRUNC(SYSDATE) - TRUNC(V_FECHA_REGISTRO);
END FN_ANTIGUEDAD_USUARIO_DIAS;
/

