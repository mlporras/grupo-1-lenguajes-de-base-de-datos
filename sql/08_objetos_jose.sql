CREATE OR REPLACE PACKAGE PKG_VALIDACIONES AS
    FUNCTION FN_USUARIO_ACTIVO(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER;
    FUNCTION FN_LIMITE_PRESTAMOS_SUPERADO(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER;
    FUNCTION FN_USUARIO_CON_MULTAS_PENDIENTES(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER;
    PROCEDURE VALIDAR_PRESTAMO(
        P_CEDULA    IN  USUARIOS.CEDULA%TYPE,
        P_RESULTADO OUT VARCHAR2
    );
END PKG_VALIDACIONES;
/

CREATE OR REPLACE PACKAGE BODY PKG_VALIDACIONES AS

    FUNCTION FN_USUARIO_ACTIVO(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_USUARIO IS
            SELECT CEDULA FROM USUARIOS WHERE CEDULA = P_CEDULA AND ESTADO = 'A';
    BEGIN
        FOR REG IN C_USUARIO LOOP
            V_TOTAL := 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_USUARIO_ACTIVO;

    FUNCTION FN_LIMITE_PRESTAMOS_SUPERADO(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
    BEGIN
        -- Reutiliza la funcion que ya existe en PKG_PRESTAMOS (de Marco)
        IF PKG_PRESTAMOS.FN_PRESTAMOS_ACTIVOS_USUARIO(P_CEDULA) >= 3 THEN
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;
    END FN_LIMITE_PRESTAMOS_SUPERADO;

    FUNCTION FN_USUARIO_CON_MULTAS_PENDIENTES(P_CEDULA IN USUARIOS.CEDULA%TYPE) RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_MULTAS IS
            SELECT ID_MULTA FROM MULTAS
            WHERE CEDULA = P_CEDULA AND ESTADO_PAGO = 'PENDIENTE';
    BEGIN
        FOR REG IN C_MULTAS LOOP
            V_TOTAL := 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_USUARIO_CON_MULTAS_PENDIENTES;

    PROCEDURE VALIDAR_PRESTAMO(
        P_CEDULA    IN  USUARIOS.CEDULA%TYPE,
        P_RESULTADO OUT VARCHAR2
    ) IS
    BEGIN
        IF FN_USUARIO_ACTIVO(P_CEDULA) = 0 THEN
            P_RESULTADO := 'USUARIO_INACTIVO_O_NO_EXISTE';
        ELSIF FN_USUARIO_CON_MULTAS_PENDIENTES(P_CEDULA) = 1 THEN
            P_RESULTADO := 'USUARIO_CON_MULTAS_PENDIENTES';
        ELSIF FN_LIMITE_PRESTAMOS_SUPERADO(P_CEDULA) = 1 THEN
            P_RESULTADO := 'LIMITE_DE_PRESTAMOS_ALCANZADO';
        ELSE
            P_RESULTADO := 'OK';
        END IF;
    END VALIDAR_PRESTAMO;

END PKG_VALIDACIONES;
/

