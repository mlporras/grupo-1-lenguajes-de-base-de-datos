-- PKG_TIPOS_MATERIAL
CREATE OR REPLACE PACKAGE BODY PKG_TIPOS_MATERIAL AS

    PROCEDURE CREAR_TIPO_MATERIAL(
        P_NOMBRE      IN TIPOS_MATERIAL.NOMBRE%TYPE,
        P_DESCRIPCION IN TIPOS_MATERIAL.DESCRIPCION%TYPE
    ) IS
    BEGIN
        INSERT INTO TIPOS_MATERIAL (ID_TIPO_MATERIAL, NOMBRE, DESCRIPCION)
        VALUES (SEQ_TIPOS_MATERIAL.NEXTVAL, P_NOMBRE, P_DESCRIPCION);
    END CREAR_TIPO_MATERIAL;

    PROCEDURE ACTUALIZAR_TIPO_MATERIAL(
        P_ID_TIPO_MATERIAL IN TIPOS_MATERIAL.ID_TIPO_MATERIAL%TYPE,
        P_NOMBRE           IN TIPOS_MATERIAL.NOMBRE%TYPE,
        P_DESCRIPCION      IN TIPOS_MATERIAL.DESCRIPCION%TYPE
    ) IS
    BEGIN
        UPDATE TIPOS_MATERIAL
        SET NOMBRE = P_NOMBRE, DESCRIPCION = P_DESCRIPCION
        WHERE ID_TIPO_MATERIAL = P_ID_TIPO_MATERIAL;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Tipo de material no encontrado.');
        END IF;
    END ACTUALIZAR_TIPO_MATERIAL;

    PROCEDURE INACTIVAR_TIPO_MATERIAL(
        P_ID_TIPO_MATERIAL IN TIPOS_MATERIAL.ID_TIPO_MATERIAL%TYPE
    ) IS
    BEGIN
        UPDATE TIPOS_MATERIAL SET ESTADO = 'I'
        WHERE ID_TIPO_MATERIAL = P_ID_TIPO_MATERIAL;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Tipo de material no encontrado.');
        END IF;
    END INACTIVAR_TIPO_MATERIAL;

    PROCEDURE OBTENER_TIPO_MATERIAL(
        P_ID_TIPO_MATERIAL IN  TIPOS_MATERIAL.ID_TIPO_MATERIAL%TYPE,
        P_RESULTADO        OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT ID_TIPO_MATERIAL, NOMBRE, DESCRIPCION, ESTADO
            FROM TIPOS_MATERIAL
            WHERE ID_TIPO_MATERIAL = P_ID_TIPO_MATERIAL;
    END OBTENER_TIPO_MATERIAL;

    PROCEDURE LISTAR_TIPOS_MATERIAL(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT ID_TIPO_MATERIAL, NOMBRE, DESCRIPCION, ESTADO
            FROM TIPOS_MATERIAL
            ORDER BY NOMBRE;
    END LISTAR_TIPOS_MATERIAL;

END PKG_TIPOS_MATERIAL;
