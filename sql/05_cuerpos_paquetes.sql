-- PKG_MATERIALES
CREATE OR REPLACE PACKAGE BODY PKG_MATERIALES AS

    PROCEDURE CREAR_MATERIAL(
        P_TITULO           IN MATERIALES.TITULO%TYPE,
        P_AUTOR            IN MATERIALES.AUTOR%TYPE,
        P_EDITORIAL        IN MATERIALES.EDITORIAL%TYPE,
        P_ANIO_PUBLICACION IN MATERIALES.ANIO_PUBLICACION%TYPE,
        P_CODIGO_ISBN      IN MATERIALES.CODIGO_ISBN%TYPE,
        P_ID_TIPO_MATERIAL IN MATERIALES.ID_TIPO_MATERIAL%TYPE,
        P_ID_CATEGORIA     IN MATERIALES.ID_CATEGORIA%TYPE
    ) IS
    BEGIN
        INSERT INTO MATERIALES (ID_MATERIAL, TITULO, AUTOR, EDITORIAL,
                                ANIO_PUBLICACION, CODIGO_ISBN,
                                ID_TIPO_MATERIAL, ID_CATEGORIA)
        VALUES (SEQ_MATERIALES.NEXTVAL, P_TITULO, P_AUTOR, P_EDITORIAL,
                P_ANIO_PUBLICACION, P_CODIGO_ISBN,
                P_ID_TIPO_MATERIAL, P_ID_CATEGORIA);
    END CREAR_MATERIAL;

    PROCEDURE ACTUALIZAR_MATERIAL(
        P_ID_MATERIAL      IN MATERIALES.ID_MATERIAL%TYPE,
        P_TITULO           IN MATERIALES.TITULO%TYPE,
        P_AUTOR            IN MATERIALES.AUTOR%TYPE,
        P_EDITORIAL        IN MATERIALES.EDITORIAL%TYPE,
        P_ANIO_PUBLICACION IN MATERIALES.ANIO_PUBLICACION%TYPE,
        P_CODIGO_ISBN      IN MATERIALES.CODIGO_ISBN%TYPE,
        P_ID_TIPO_MATERIAL IN MATERIALES.ID_TIPO_MATERIAL%TYPE,
        P_ID_CATEGORIA     IN MATERIALES.ID_CATEGORIA%TYPE
    ) IS
    BEGIN
        UPDATE MATERIALES
        SET TITULO = P_TITULO, AUTOR = P_AUTOR, EDITORIAL = P_EDITORIAL,
            ANIO_PUBLICACION = P_ANIO_PUBLICACION, CODIGO_ISBN = P_CODIGO_ISBN,
            ID_TIPO_MATERIAL = P_ID_TIPO_MATERIAL, ID_CATEGORIA = P_ID_CATEGORIA
        WHERE ID_MATERIAL = P_ID_MATERIAL;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20020, 'Material no encontrado.');
        END IF;
    END ACTUALIZAR_MATERIAL;

    PROCEDURE INACTIVAR_MATERIAL(
        P_ID_MATERIAL IN MATERIALES.ID_MATERIAL%TYPE
    ) IS
    BEGIN
        UPDATE MATERIALES SET ESTADO = 'INACTIVO'
        WHERE ID_MATERIAL = P_ID_MATERIAL;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20021, 'Material no encontrado.');
        END IF;
    END INACTIVAR_MATERIAL;

    PROCEDURE OBTENER_MATERIAL(
        P_ID_MATERIAL IN  MATERIALES.ID_MATERIAL%TYPE,
        P_RESULTADO   OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT M.ID_MATERIAL, M.TITULO, M.AUTOR, M.EDITORIAL,
                   M.ANIO_PUBLICACION, M.CODIGO_ISBN,
                   M.ID_TIPO_MATERIAL, M.ID_CATEGORIA, M.ESTADO,
                   T.NOMBRE AS TIPO_NOMBRE, C.NOMBRE AS CATEGORIA_NOMBRE
            FROM MATERIALES M
            JOIN TIPOS_MATERIAL T ON M.ID_TIPO_MATERIAL = T.ID_TIPO_MATERIAL
            JOIN CATEGORIAS C    ON M.ID_CATEGORIA = C.ID_CATEGORIA
            WHERE M.ID_MATERIAL = P_ID_MATERIAL;
    END OBTENER_MATERIAL;

    PROCEDURE LISTAR_MATERIALES(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT M.ID_MATERIAL, M.TITULO, M.AUTOR, M.EDITORIAL,
                   M.ANIO_PUBLICACION, M.CODIGO_ISBN,
                   M.ID_TIPO_MATERIAL, M.ID_CATEGORIA, M.ESTADO,
                   T.NOMBRE AS TIPO_NOMBRE, C.NOMBRE AS CATEGORIA_NOMBRE
            FROM MATERIALES M
            JOIN TIPOS_MATERIAL T ON M.ID_TIPO_MATERIAL = T.ID_TIPO_MATERIAL
            JOIN CATEGORIAS C    ON M.ID_CATEGORIA = C.ID_CATEGORIA
            ORDER BY M.TITULO;
    END LISTAR_MATERIALES;

    PROCEDURE BUSCAR_MATERIALES(
        P_TEXTO     IN  VARCHAR2,
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT M.ID_MATERIAL, M.TITULO, M.AUTOR, M.EDITORIAL,
                   M.ANIO_PUBLICACION, M.CODIGO_ISBN,
                   M.ID_TIPO_MATERIAL, M.ID_CATEGORIA, M.ESTADO,
                   T.NOMBRE AS TIPO_NOMBRE, C.NOMBRE AS CATEGORIA_NOMBRE
            FROM MATERIALES M
            JOIN TIPOS_MATERIAL T ON M.ID_TIPO_MATERIAL = T.ID_TIPO_MATERIAL
            JOIN CATEGORIAS C    ON M.ID_CATEGORIA = C.ID_CATEGORIA
            WHERE UPPER(M.TITULO) LIKE '%' || UPPER(P_TEXTO) || '%'
               OR UPPER(M.AUTOR)  LIKE '%' || UPPER(P_TEXTO) || '%'
               OR UPPER(C.NOMBRE) LIKE '%' || UPPER(P_TEXTO) || '%'
            ORDER BY M.TITULO;
    END BUSCAR_MATERIALES;

    FUNCTION FN_MATERIAL_DISPONIBLE(
        P_ID_MATERIAL IN MATERIALES.ID_MATERIAL%TYPE
    ) RETURN NUMBER IS
        V_ESTADO MATERIALES.ESTADO%TYPE;
    BEGIN
        SELECT ESTADO INTO V_ESTADO
        FROM MATERIALES WHERE ID_MATERIAL = P_ID_MATERIAL;
        IF V_ESTADO = 'DISPONIBLE' THEN RETURN 1; ELSE RETURN 0; END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 0;
    END FN_MATERIAL_DISPONIBLE;

END PKG_MATERIALES;
