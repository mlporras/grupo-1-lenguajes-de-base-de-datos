-- PKG_PRESTAMOS
CREATE OR REPLACE PACKAGE BODY PKG_PRESTAMOS AS

    PROCEDURE REGISTRAR_PRESTAMO(
        P_CEDULA                    IN PRESTAMOS.CEDULA%TYPE,
        P_ID_MATERIAL               IN PRESTAMOS.ID_MATERIAL%TYPE,
        P_FECHA_DEVOLUCION_ESPERADA IN PRESTAMOS.FECHA_DEVOLUCION_ESPERADA%TYPE
    ) IS
        V_ESTADO_USUARIO USUARIOS.ESTADO%TYPE;
        V_ESTADO_MATERIAL MATERIALES.ESTADO%TYPE;
        V_ACTIVOS NUMBER;
    BEGIN
        BEGIN
            SELECT ESTADO INTO V_ESTADO_USUARIO FROM USUARIOS WHERE CEDULA = P_CEDULA;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20030, 'El usuario no existe.');
        END;
        IF V_ESTADO_USUARIO != 'A' THEN
            RAISE_APPLICATION_ERROR(-20031, 'El usuario no esta activo.');
        END IF;

        BEGIN
            SELECT ESTADO INTO V_ESTADO_MATERIAL FROM MATERIALES WHERE ID_MATERIAL = P_ID_MATERIAL;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20032, 'El material no existe.');
        END;
        IF V_ESTADO_MATERIAL != 'DISPONIBLE' THEN
            RAISE_APPLICATION_ERROR(-20033, 'El material no esta disponible.');
        END IF;

        SELECT COUNT(*) INTO V_ACTIVOS FROM PRESTAMOS
        WHERE ID_MATERIAL = P_ID_MATERIAL AND ESTADO = 'ACTIVO';
        IF V_ACTIVOS > 0 THEN
            RAISE_APPLICATION_ERROR(-20034, 'El material ya tiene un prestamo activo.');
        END IF;

        IF P_FECHA_DEVOLUCION_ESPERADA < TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20035, 'La fecha de devolucion no puede ser anterior a hoy.');
        END IF;

        INSERT INTO PRESTAMOS (ID_PRESTAMO, CEDULA, ID_MATERIAL, FECHA_DEVOLUCION_ESPERADA)
        VALUES (SEQ_PRESTAMOS.NEXTVAL, P_CEDULA, P_ID_MATERIAL, P_FECHA_DEVOLUCION_ESPERADA);

        UPDATE MATERIALES SET ESTADO = 'PRESTADO' WHERE ID_MATERIAL = P_ID_MATERIAL;
    END REGISTRAR_PRESTAMO;

    PROCEDURE REGISTRAR_DEVOLUCION(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE
    ) IS
        V_ESTADO      PRESTAMOS.ESTADO%TYPE;
        V_ID_MATERIAL PRESTAMOS.ID_MATERIAL%TYPE;
    BEGIN
        BEGIN
            SELECT ESTADO, ID_MATERIAL INTO V_ESTADO, V_ID_MATERIAL
            FROM PRESTAMOS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20036, 'El prestamo no existe.');
        END;
        IF V_ESTADO != 'ACTIVO' THEN
            RAISE_APPLICATION_ERROR(-20037, 'El prestamo ya fue devuelto o anulado.');
        END IF;

        UPDATE PRESTAMOS
        SET FECHA_DEVOLUCION_REAL = SYSDATE, ESTADO = 'DEVUELTO'
        WHERE ID_PRESTAMO = P_ID_PRESTAMO;

        UPDATE MATERIALES SET ESTADO = 'DISPONIBLE' WHERE ID_MATERIAL = V_ID_MATERIAL;
    END REGISTRAR_DEVOLUCION;

    PROCEDURE ANULAR_PRESTAMO(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE
    ) IS
        V_ESTADO      PRESTAMOS.ESTADO%TYPE;
        V_ID_MATERIAL PRESTAMOS.ID_MATERIAL%TYPE;
    BEGIN
        BEGIN
            SELECT ESTADO, ID_MATERIAL INTO V_ESTADO, V_ID_MATERIAL
            FROM PRESTAMOS WHERE ID_PRESTAMO = P_ID_PRESTAMO;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20038, 'El prestamo no existe.');
        END;
        IF V_ESTADO != 'ACTIVO' THEN
            RAISE_APPLICATION_ERROR(-20039, 'Solo se pueden anular prestamos activos.');
        END IF;

        UPDATE PRESTAMOS SET ESTADO = 'ANULADO' WHERE ID_PRESTAMO = P_ID_PRESTAMO;
        UPDATE MATERIALES SET ESTADO = 'DISPONIBLE' WHERE ID_MATERIAL = V_ID_MATERIAL;
    END ANULAR_PRESTAMO;

    PROCEDURE OBTENER_PRESTAMO(
        P_ID_PRESTAMO IN  PRESTAMOS.ID_PRESTAMO%TYPE,
        P_RESULTADO   OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT P.ID_PRESTAMO, P.CEDULA, P.ID_MATERIAL,
                   P.FECHA_PRESTAMO, P.FECHA_DEVOLUCION_ESPERADA,
                   P.FECHA_DEVOLUCION_REAL, P.ESTADO,
                   U.NOMBRE || ' ' || U.APELLIDOS AS NOMBRE_USUARIO,
                   M.TITULO AS TITULO_MATERIAL
            FROM PRESTAMOS P
            JOIN USUARIOS U  ON P.CEDULA = U.CEDULA
            JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
            WHERE P.ID_PRESTAMO = P_ID_PRESTAMO;
    END OBTENER_PRESTAMO;

    PROCEDURE LISTAR_PRESTAMOS(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT P.ID_PRESTAMO, P.CEDULA, P.ID_MATERIAL,
                   P.FECHA_PRESTAMO, P.FECHA_DEVOLUCION_ESPERADA,
                   P.FECHA_DEVOLUCION_REAL, P.ESTADO,
                   U.NOMBRE || ' ' || U.APELLIDOS AS NOMBRE_USUARIO,
                   M.TITULO AS TITULO_MATERIAL
            FROM PRESTAMOS P
            JOIN USUARIOS U  ON P.CEDULA = U.CEDULA
            JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
            ORDER BY P.FECHA_PRESTAMO DESC;
    END LISTAR_PRESTAMOS;

    PROCEDURE LISTAR_PRESTAMOS_ACTIVOS(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT P.ID_PRESTAMO, P.CEDULA, P.ID_MATERIAL,
                   P.FECHA_PRESTAMO, P.FECHA_DEVOLUCION_ESPERADA,
                   P.FECHA_DEVOLUCION_REAL, P.ESTADO,
                   U.NOMBRE || ' ' || U.APELLIDOS AS NOMBRE_USUARIO,
                   M.TITULO AS TITULO_MATERIAL
            FROM PRESTAMOS P
            JOIN USUARIOS U  ON P.CEDULA = U.CEDULA
            JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
            WHERE P.ESTADO = 'ACTIVO'
            ORDER BY P.FECHA_PRESTAMO DESC;
    END LISTAR_PRESTAMOS_ACTIVOS;

    PROCEDURE LISTAR_HISTORIAL_USUARIO(
        P_CEDULA    IN  USUARIOS.CEDULA%TYPE,
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT P.ID_PRESTAMO, P.ID_MATERIAL,
                   P.FECHA_PRESTAMO, P.FECHA_DEVOLUCION_ESPERADA,
                   P.FECHA_DEVOLUCION_REAL, P.ESTADO,
                   M.TITULO AS TITULO_MATERIAL
            FROM PRESTAMOS P
            JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
            WHERE P.CEDULA = P_CEDULA
            ORDER BY P.FECHA_PRESTAMO DESC;
    END LISTAR_HISTORIAL_USUARIO;

    FUNCTION FN_PRESTAMOS_ACTIVOS_USUARIO(
        P_CEDULA IN USUARIOS.CEDULA%TYPE
    ) RETURN NUMBER IS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_TOTAL FROM PRESTAMOS
        WHERE CEDULA = P_CEDULA AND ESTADO = 'ACTIVO';
        RETURN V_TOTAL;
    END FN_PRESTAMOS_ACTIVOS_USUARIO;

END PKG_PRESTAMOS;
