/

CREATE OR REPLACE VIEW VW_PRESTAMOS_ACTIVOS AS
SELECT
    P.ID_PRESTAMO,
    P.CEDULA,
    P.ID_MATERIAL,
    P.FECHA_PRESTAMO,
    P.FECHA_DEVOLUCION_ESPERADA,
    U.NOMBRE || ' ' || U.APELLIDOS AS USUARIO,
    M.TITULO AS MATERIAL
FROM PRESTAMOS P
JOIN USUARIOS U ON P.CEDULA = U.CEDULA
JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
WHERE P.ESTADO = 'ACTIVO';
/

CREATE OR REPLACE VIEW VW_PRESTAMOS_DEVUELTOS AS
SELECT
    P.ID_PRESTAMO,
    P.CEDULA,
    P.ID_MATERIAL,
    P.FECHA_PRESTAMO,
    P.FECHA_DEVOLUCION_ESPERADA,
    P.FECHA_DEVOLUCION_REAL,
    U.NOMBRE || ' ' || U.APELLIDOS AS USUARIO,
    M.TITULO AS MATERIAL
FROM PRESTAMOS P
JOIN USUARIOS U ON P.CEDULA = U.CEDULA
JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
WHERE P.ESTADO = 'DEVUELTO';
/

CREATE OR REPLACE VIEW VW_PRESTAMOS_VENCIDOS AS
SELECT
    P.ID_PRESTAMO,
    P.CEDULA,
    P.ID_MATERIAL,
    P.FECHA_PRESTAMO,
    P.FECHA_DEVOLUCION_ESPERADA,
    U.NOMBRE || ' ' || U.APELLIDOS AS USUARIO,
    M.TITULO AS MATERIAL
FROM PRESTAMOS P
JOIN USUARIOS U ON P.CEDULA = U.CEDULA
JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL
WHERE P.ESTADO = 'ACTIVO'
  AND P.FECHA_DEVOLUCION_ESPERADA < TRUNC(SYSDATE);
/

CREATE OR REPLACE VIEW VW_RESUMEN_PRESTAMOS AS
SELECT
    U.CEDULA,
    U.NOMBRE || ' ' || U.APELLIDOS AS USUARIO,
    COUNT(P.ID_PRESTAMO) AS TOTAL_PRESTAMOS,
    SUM(CASE WHEN P.ESTADO = 'ACTIVO' THEN 1 ELSE 0 END) AS ACTIVOS,
    SUM(CASE WHEN P.ESTADO = 'DEVUELTO' THEN 1 ELSE 0 END) AS DEVUELTOS,
    SUM(CASE WHEN P.ESTADO = 'ANULADO' THEN 1 ELSE 0 END) AS ANULADOS
FROM USUARIOS U
LEFT JOIN PRESTAMOS P ON U.CEDULA = P.CEDULA
GROUP BY U.CEDULA, U.NOMBRE, U.APELLIDOS;
/

CREATE OR REPLACE VIEW VW_HISTORIAL_MATERIALES AS
SELECT
    P.ID_PRESTAMO,
    U.CEDULA,
    U.NOMBRE || ' ' || U.APELLIDOS AS USUARIO,
    M.TITULO AS MATERIAL,
    P.FECHA_PRESTAMO,
    P.FECHA_DEVOLUCION_ESPERADA,
    P.FECHA_DEVOLUCION_REAL,
    P.ESTADO
FROM PRESTAMOS P
JOIN USUARIOS U ON P.CEDULA = U.CEDULA
JOIN MATERIALES M ON P.ID_MATERIAL = M.ID_MATERIAL;
/

