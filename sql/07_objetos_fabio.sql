CREATE OR REPLACE VIEW VW_MATERIALES_DISPONIBLES AS
SELECT
    M.ID_MATERIAL,
    M.TITULO,
    M.AUTOR,
    M.CODIGO_ISBN,
    T.NOMBRE AS TIPO_MATERIAL,
    C.NOMBRE AS CATEGORIA
FROM MATERIALES M
JOIN TIPOS_MATERIAL T ON M.ID_TIPO_MATERIAL = T.ID_TIPO_MATERIAL
JOIN CATEGORIAS C ON M.ID_CATEGORIA = C.ID_CATEGORIA
WHERE M.ESTADO = 'DISPONIBLE'
  AND T.ESTADO = 'A'
  AND C.ESTADO = 'A';
/

CREATE OR REPLACE VIEW VW_MATERIALES_PRESTADOS AS
SELECT
    M.ID_MATERIAL,
    M.TITULO,
    M.AUTOR,
    T.NOMBRE AS TIPO_MATERIAL,
    C.NOMBRE AS CATEGORIA
FROM MATERIALES M
JOIN TIPOS_MATERIAL T ON M.ID_TIPO_MATERIAL = T.ID_TIPO_MATERIAL
JOIN CATEGORIAS C ON M.ID_CATEGORIA = C.ID_CATEGORIA
WHERE M.ESTADO = 'PRESTADO';
/

CREATE OR REPLACE VIEW VW_MATERIALES_INACTIVOS AS
SELECT
    M.ID_MATERIAL,
    M.TITULO,
    M.AUTOR,
    M.CODIGO_ISBN,
    M.ESTADO
FROM MATERIALES M
WHERE M.ESTADO = 'INACTIVO';
/

CREATE OR REPLACE VIEW VW_USUARIOS_ACTIVOS AS
SELECT
    U.CEDULA,
    U.NOMBRE,
    U.APELLIDOS,
    U.CORREO,
    U.TELEFONO,
    U.FECHA_REGISTRO
FROM USUARIOS U
WHERE U.ESTADO = 'A';
/

CREATE OR REPLACE VIEW VW_USUARIOS_INACTIVOS AS
SELECT
    U.CEDULA,
    U.NOMBRE,
    U.APELLIDOS,
    U.CORREO,
    U.TELEFONO,
    U.FECHA_REGISTRO
FROM USUARIOS U
