CREATE OR REPLACE PACKAGE BODY PKG_CONSULTAS AS

    PROCEDURE CONSULTAR_MATERIALES_POR_CATEGORIA(
        P_ID_CATEGORIA IN CATEGORIAS.ID_CATEGORIA%TYPE,
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM VW_MATERIALES_DISPONIBLES
            WHERE CATEGORIA = (
                SELECT NOMBRE
                FROM CATEGORIAS
                WHERE ID_CATEGORIA = P_ID_CATEGORIA
            );
    END CONSULTAR_MATERIALES_POR_CATEGORIA;

    PROCEDURE CONSULTAR_HISTORIAL_POR_USUARIO(
        P_CEDULA IN USUARIOS.CEDULA%TYPE,
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM VW_HISTORIAL_MATERIALES
            WHERE CEDULA = P_CEDULA
            ORDER BY FECHA_PRESTAMO DESC;
    END CONSULTAR_HISTORIAL_POR_USUARIO;

