    FUNCTION FN_TOTAL_MATERIALES_DISPONIBLES RETURN NUMBER;
    FUNCTION FN_TOTAL_PRESTAMOS_ACTIVOS RETURN NUMBER;
    FUNCTION FN_TOTAL_USUARIOS_ACTIVOS RETURN NUMBER;
    FUNCTION FN_PRESTAMOS_VENCIDOS RETURN NUMBER;
    FUNCTION FN_TOTAL_MATERIALES_POR_TIPO(
        P_ID_TIPO_MATERIAL IN TIPOS_MATERIAL.ID_TIPO_MATERIAL%TYPE
    ) RETURN NUMBER;
    FUNCTION FN_DIAS_RETRASO(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE
    ) RETURN NUMBER;
    FUNCTION FN_MATERIAL_MAS_PRESTADO RETURN NUMBER;

END PKG_REPORTES;
/

CREATE OR REPLACE PACKAGE BODY PKG_REPORTES AS

    PROCEDURE REPORTE_MATERIALES_DISPONIBLES(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM VW_MATERIALES_DISPONIBLES
            ORDER BY TITULO;
    END REPORTE_MATERIALES_DISPONIBLES;

    PROCEDURE REPORTE_PRESTAMOS_VENCIDOS(
        P_RESULTADO OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN P_RESULTADO FOR
            SELECT *
            FROM VW_PRESTAMOS_VENCIDOS
            ORDER BY FECHA_DEVOLUCION_ESPERADA;
    END REPORTE_PRESTAMOS_VENCIDOS;

    PROCEDURE MARCAR_PRESTAMOS_VENCIDOS IS
        CURSOR C_VENCIDOS IS
            SELECT ID_PRESTAMO
            FROM PRESTAMOS
            WHERE ESTADO = 'ACTIVO'
              AND FECHA_DEVOLUCION_ESPERADA < TRUNC(SYSDATE);
    BEGIN
        FOR REG IN C_VENCIDOS LOOP
            UPDATE PRESTAMOS
            SET ESTADO = 'ANULADO'
            WHERE ID_PRESTAMO = REG.ID_PRESTAMO;
        END LOOP;
    END MARCAR_PRESTAMOS_VENCIDOS;

    FUNCTION FN_TOTAL_MATERIALES_DISPONIBLES RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_DISPONIBLES IS
            SELECT ID_MATERIAL
            FROM MATERIALES
            WHERE ESTADO = 'DISPONIBLE';
    BEGIN
        FOR REG IN C_DISPONIBLES LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_TOTAL_MATERIALES_DISPONIBLES;

    FUNCTION FN_TOTAL_PRESTAMOS_ACTIVOS RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_ACTIVOS IS
            SELECT ID_PRESTAMO
            FROM PRESTAMOS
            WHERE ESTADO = 'ACTIVO';
    BEGIN
        FOR REG IN C_ACTIVOS LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_TOTAL_PRESTAMOS_ACTIVOS;

    FUNCTION FN_TOTAL_USUARIOS_ACTIVOS RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_USUARIOS IS
            SELECT CEDULA
            FROM USUARIOS
            WHERE ESTADO = 'A';
    BEGIN
        FOR REG IN C_USUARIOS LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_TOTAL_USUARIOS_ACTIVOS;

    FUNCTION FN_PRESTAMOS_VENCIDOS RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_VENCIDOS IS
            SELECT ID_PRESTAMO
            FROM PRESTAMOS
            WHERE ESTADO = 'ACTIVO'
              AND FECHA_DEVOLUCION_ESPERADA < TRUNC(SYSDATE);
    BEGIN
        FOR REG IN C_VENCIDOS LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_PRESTAMOS_VENCIDOS;

    FUNCTION FN_TOTAL_MATERIALES_POR_TIPO(
        P_ID_TIPO_MATERIAL IN TIPOS_MATERIAL.ID_TIPO_MATERIAL%TYPE
    ) RETURN NUMBER IS
        V_TOTAL NUMBER := 0;
        CURSOR C_TIPO IS
            SELECT ID_MATERIAL
            FROM MATERIALES
            WHERE ID_TIPO_MATERIAL = P_ID_TIPO_MATERIAL;
    BEGIN
        FOR REG IN C_TIPO LOOP
            V_TOTAL := V_TOTAL + 1;
        END LOOP;
        RETURN V_TOTAL;
    END FN_TOTAL_MATERIALES_POR_TIPO;

    FUNCTION FN_DIAS_RETRASO(
        P_ID_PRESTAMO IN PRESTAMOS.ID_PRESTAMO%TYPE
    ) RETURN NUMBER IS
        V_DIAS NUMBER := 0;
        CURSOR C_PRESTAMO IS
            SELECT FECHA_DEVOLUCION_ESPERADA, FECHA_DEVOLUCION_REAL
            FROM PRESTAMOS
            WHERE ID_PRESTAMO = P_ID_PRESTAMO;
    BEGIN
        FOR REG IN C_PRESTAMO LOOP
            IF REG.FECHA_DEVOLUCION_REAL IS NOT NULL THEN
                V_DIAS := TRUNC(REG.FECHA_DEVOLUCION_REAL - REG.FECHA_DEVOLUCION_ESPERADA);
            ELSE
                V_DIAS := TRUNC(SYSDATE - REG.FECHA_DEVOLUCION_ESPERADA);
            END IF;
        END LOOP;
        RETURN NVL(V_DIAS, 0);
    END FN_DIAS_RETRASO;

    FUNCTION FN_MATERIAL_MAS_PRESTADO RETURN NUMBER IS
        V_ID_MATERIAL NUMBER := NULL;
        CURSOR C_MAS_PRESTADO IS
            SELECT ID_MATERIAL
            FROM (
                SELECT ID_MATERIAL, COUNT(*) AS CNT
                FROM PRESTAMOS
                GROUP BY ID_MATERIAL
            )
            WHERE CNT = (
                SELECT MAX(CNT)
                FROM (
                    SELECT COUNT(*) AS CNT
                    FROM PRESTAMOS
                    GROUP BY ID_MATERIAL
                )
            );
    BEGIN
        FOR REG IN C_MAS_PRESTADO LOOP
            V_ID_MATERIAL := REG.ID_MATERIAL;
            EXIT;
        END LOOP;
        RETURN V_ID_MATERIAL;
    END FN_MATERIAL_MAS_PRESTADO;

END PKG_REPORTES;
